/**
 * Generates platform theme files from src/tokens.ts:
 *   web.css     shadcn convention (Tailwind v4): :root/.dark raw vars + @theme inline mapping
 *   native.css  Uniwind convention (Tailwind v4): @layer theme { :root { @variant light|dark } }
 *   colors.ts   hex values for React Native APIs that cannot read CSS (navigation, icons)
 */
import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { formatHex, formatHex8, parse } from "culori"

import { colors, fontFamily, radius, radiusScale, type ColorToken } from "../src/tokens.ts"

const out = (file: string) => fileURLToPath(new URL(`../src/generated/${file}`, import.meta.url))
const HEADER = "/* GENERATED by packages/theme/scripts/generate.ts — edit src/tokens.ts instead. */"

const kebab = (token: string) => token.replace(/([a-z])([A-Z0-9])/g, "$1-$2").toLowerCase()
const tokens = Object.keys(colors.light) as ColorToken[]
const radii = Object.entries(radiusScale).map(
  ([name, factor]) => `--radius-${name}: ${+(radius * factor).toFixed(4)}rem;`
)

const vars = (scheme: keyof typeof colors, prefix: string) =>
  tokens.map((t) => `${prefix}${kebab(t)}: ${colors[scheme][t]};`).join("\n")

const web = `${HEADER}
:root {
--radius: ${radius}rem;
${vars("light", "--")}
}

.dark {
${vars("dark", "--")}
}

@theme inline {
${tokens.map((t) => `--color-${kebab(t)}: var(--${kebab(t)});`).join("\n")}
${radii.join("\n")}
}
`

const native = `${HEADER}
@theme {
--radius: ${radius}rem;
${radii.join("\n")}
--font-sans: "${fontFamily.sans}";
}

@layer theme {
:root {
@variant light {
${vars("light", "--color-")}
}
@variant dark {
${vars("dark", "--color-")}
}
}
}
`

const toHex = (value: string) => {
  const color = parse(value)
  if (!color) throw new Error(`Invalid color: ${value}`)
  return color.alpha !== undefined && color.alpha < 1 ? formatHex8(color) : formatHex(color)
}
const hexTheme = Object.fromEntries(
  Object.entries(colors).map(([scheme, values]) => [
    scheme,
    Object.fromEntries(Object.entries(values).map(([k, v]) => [k, toHex(v)])),
  ])
)

const ts = `${HEADER.replace("/*", "//").replace(" */", "")}
export const hexColors = ${JSON.stringify(hexTheme, null, 2)} as const
`

writeFileSync(out("web.css"), web)
writeFileSync(out("native.css"), native)
writeFileSync(out("colors.ts"), ts)
console.log("Theme generated: web.css, native.css, colors.ts")
